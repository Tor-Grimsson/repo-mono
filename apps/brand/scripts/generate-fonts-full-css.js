#!/usr/bin/env node
/**
 * Walks public/fonts/Right-Grotesk/ and emits @font-face declarations for every
 * .woff2 cut, grouped by width axis (base / Compact / Tall / Wide / Narrow /
 * Spatial / Tight). Output: src/styles/kol-fonts-full.css.
 *
 * The output file is not imported anywhere — it sits dormant until the social
 * post generator (or other content tool) needs the full family.
 *
 * Regenerate: node scripts/generate-fonts-full-css.js
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const FONTS_DIR = path.join(ROOT, 'public/fonts/Right-Grotesk')
const OUT = path.join(ROOT, 'src/styles/kol-fonts-full.css')

// PP weight convention
const WEIGHTS = {
  Fine:    100,
  Light:   300,
  Regular: 400,
  Medium:  500,
  Dark:    600,
  Bold:    700,
  Black:   900,
}

// Width-axis cuts (filename prefix). Empty = base "Right Grotesk".
const WIDTHS = ['Compact', 'Tall', 'Wide', 'Narrow', 'Spatial', 'Tight']

// Order weights longest-first so e.g. "Black" beats nothing accidentally short-circuiting
const WEIGHT_NAMES = Object.keys(WEIGHTS).sort((a, b) => b.length - a.length)

function parse(file) {
  const m = file.match(/^PPRightGrotesk-(.+)\.woff2$/)
  if (!m) return null
  let tail = m[1]

  const italic = tail.endsWith('Italic')
  if (italic) tail = tail.slice(0, -'Italic'.length)

  let weightName = null
  for (const w of WEIGHT_NAMES) {
    if (tail.endsWith(w)) {
      weightName = w
      tail = tail.slice(0, -w.length)
      break
    }
  }
  if (!weightName) return null

  const width = tail || '' // remaining is width prefix, or empty for base
  if (width && !WIDTHS.includes(width)) return null

  return {
    file,
    width,
    family: width ? `Right Grotesk ${width}` : 'Right Grotesk',
    weight: WEIGHTS[weightName],
    italic,
  }
}

function emit(c) {
  return `@font-face {
  font-family: "${c.family}";
  src: url("/fonts/Right-Grotesk/${c.file}") format("woff2");
  font-weight: ${c.weight};
  font-style: ${c.italic ? 'italic' : 'normal'};
  font-display: swap;
}
`
}

function main() {
  const files = fs.readdirSync(FONTS_DIR).filter(f => f.endsWith('.woff2')).sort()
  const cuts = files.map(parse).filter(Boolean)
  const skipped = files.length - cuts.length

  // Group by width
  const groups = new Map()
  for (const c of cuts) {
    const key = c.width || 'base'
    if (!groups.has(key)) groups.set(key, [])
    groups.get(key).push(c)
  }

  const order = ['base', ...WIDTHS]
  const out = []

  out.push('/**')
  out.push(' * KOL Fonts — Full Right Grotesk family')
  out.push(' *')
  out.push(' * Auto-generated by scripts/generate-fonts-full-css.js. Do not edit by hand.')
  out.push(' *')
  out.push(' * Not imported anywhere by default. Import this stylesheet from generator /')
  out.push(' * content-creation routes only (e.g. social post composer). Browsers lazy-')
  out.push(' * load font files — declaring @font-face does not download them until a')
  out.push(' * matching CSS rule actually uses them.')
  out.push(' */')
  out.push('')

  for (const key of order) {
    const list = groups.get(key)
    if (!list) continue
    const label = key === 'base' ? 'Right Grotesk (base, display)' : `Right Grotesk ${key}`
    out.push('/* ════════════════════════════════════════════════════════════')
    out.push(`   ${label.toUpperCase()}`)
    out.push('   ════════════════════════════════════════════════════════════ */')
    out.push('')
    list.sort((a, b) => a.weight - b.weight || Number(a.italic) - Number(b.italic))
    for (const c of list) out.push(emit(c))
  }

  fs.writeFileSync(OUT, out.join('\n'))
  console.log(`wrote ${cuts.length} @font-face blocks to ${path.relative(ROOT, OUT)}`)
  if (skipped) console.log(`skipped ${skipped} unparseable file(s)`)
}

main()
